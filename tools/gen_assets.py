#!/usr/bin/env python3
"""Generate precomputed math tables (src/tables.asm) and open-world city map +
6-chapter / 12-leg courier storyline (src/world.asm) for SpecDrive 3D.
"""

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def to_s8(val: int) -> int:
    val = max(-127, min(127, val))
    return val & 0xFF


def fmt_db(values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append("    db " + ", ".join(f"${v:02X}" for v in chunk))
    return "\n".join(lines)


def generate_tables():
    # 1. SinTable (320 bytes: 0..255 + 64 wrap so CosTable = SinTable + 64)
    sin_tbl = [
        to_s8(int(round(127.0 * math.sin(a * 2.0 * math.pi / 256.0))))
        for a in range(320)
    ]

    # 2. InvAbsCos and InvAbsSin (split Lo/Hi 256-byte tables, clamped to 4095)
    inv_cos_lo, inv_cos_hi = [], []
    inv_sin_lo, inv_sin_hi = [], []
    for a in range(256):
        rad = a * 2.0 * math.pi / 256.0
        c = abs(math.cos(rad))
        s = abs(math.sin(rad))
        vc = 4095 if c < (256.0 / 4095.0) else min(4095, int(round(256.0 / c)))
        vs = 4095 if s < (256.0 / 4095.0) else min(4095, int(round(256.0 / s)))
        inv_cos_lo.append(vc & 0xFF)
        inv_cos_hi.append((vc >> 8) & 0xFF)
        inv_sin_lo.append(vs & 0xFF)
        inv_sin_hi.append((vs >> 8) & 0xFF)

    # 3. WallHeightTable (256 bytes: perpDist8 -> base half-height below horizon 0..32)
    wall_h = []
    for d in range(256):
        if d == 0:
            h = 32
        elif d >= 216:
            h = 0
        else:
            h = min(32, max(1, int(round(24.0 * 16.0 / d))))
        wall_h.append(h)

    # 4. FisheyeCos (32 bytes for 32 rays across 90-deg FOV)
    fisheye32 = []
    for col in range(32):
        rad = ((col * 2) - 31.0) * 2.0 * math.pi / 256.0
        fisheye32.append(min(255, int(round(256.0 * math.cos(rad)))))

    # 5. RowDistDiv16 (8 bytes for 8 ground char-row bands b = 0..7 below horizon)
    row_dist_div16 = []
    for b in range(8):
        dy = b * 4.0 + 2.5
        val = min(255, max(1, int(round(24.0 * 16.0 / dy))))
        row_dist_div16.append(val)

    # 6. SkylineTable (256 bytes: distant rolling hills + city skyline height 1..10 buffer rows)
    skyline = []
    for a in range(256):
        rad = a * 2.0 * math.pi / 256.0
        hill = (
            3.5
            + 2.2 * math.sin(rad * 2.0 + 0.4)
            + 1.6 * math.sin(rad * 5.0 + 1.2)
            + 1.0 * math.cos(rad * 11.0)
        )
        if 170 <= a <= 215 and ((a // 3) % 2 == 0):
            hill = max(hill, 6.0 + ((a * 7) % 4))
        elif 20 <= a <= 55 and ((a // 4) % 2 == 0):
            hill = max(hill, 5.0 + ((a * 5) % 4))
        skyline.append(max(1, min(10, int(round(hill)))))

    # 7. ScreenRowAddr (192 entries split into ScrRowLo / ScrRowHi, 256-byte aligned)
    scr_lo, scr_hi = [], []
    for y in range(192):
        hi = 0x40 | (y & 0x07) | ((y & 0xC0) >> 3)
        lo = ((y & 0x38) << 2)
        scr_lo.append(lo)
        scr_hi.append(hi)
    scr_lo.extend([0] * 64)
    scr_hi.extend([0] * 64)

    out = []
    out.append("; ==============================================================================")
    out.append("; AUTO-GENERATED BY tools/gen_assets.py — DO NOT EDIT BY HAND")
    out.append("; Page-aligned lookup tables for Z80 32-ray DDA raycaster & ground caster")
    out.append("; ==============================================================================")
    out.append("")
    out.append("    ORG $B200")
    out.append("")
    out.append("InvAbsCosLo:")
    out.append(fmt_db(inv_cos_lo))
    out.append("InvAbsCosHi:")
    out.append(fmt_db(inv_cos_hi))
    out.append("")
    out.append("InvAbsSinLo:")
    out.append(fmt_db(inv_sin_lo))
    out.append("InvAbsSinHi:")
    out.append(fmt_db(inv_sin_hi))
    out.append("")
    out.append("WallHeightTable:")
    out.append(fmt_db(wall_h))
    out.append("")
    out.append("SkylineTable:")
    out.append(fmt_db(skyline))
    out.append("")
    out.append("SinTable:")
    out.append(fmt_db(sin_tbl))
    out.append("CosTable EQU SinTable + 64")
    out.append("")
    out.append("    ALIGN 256")
    out.append("FisheyeCos:")
    out.append(fmt_db(fisheye32))
    out.append("")
    out.append("RowDistDiv16:")
    out.append(fmt_db(row_dist_div16))
    out.append("")
    out.append("    ALIGN 256")
    out.append("ScrRowLo:")
    out.append(fmt_db(scr_lo))
    out.append("ScrRowHi:")
    out.append(fmt_db(scr_hi))
    out.append("")

    (ROOT / "src" / "tables.asm").write_text("\n".join(out))
    print("Wrote src/tables.asm")


